package ex_16_Arrays;

public class Lab153_Arrays_Interview {
    static void main(String[] args) {

        String []names=new String[3];
        System.out.println(names[0]);//null
        System.out.println(names[1]);//null default value
        System.out.println(names[2]);//null

        //after initialize the value
        names[0]= "savita";
        names[1]= "Nikshita";
        names[2]= "Prajyot";

        System.out.println(names[0]);//savita
        System.out.println(names[1]);//Nikshita
        System.out.println(names[2]);//Prajyot



    }



    }
